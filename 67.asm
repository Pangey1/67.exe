org 0x7C00          ; Адрес загрузки MBR

start:
    ; Сброс сегментных регистров для железной стабильности
    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0x7C00

    ; Переключаемся в цветной текстовый режим 80x25
    mov ax, 0x0003
    int 0x10

    ; Отключаем мигание текста, чтобы разблокировать жирные цвета фона (все 16 цветов)
    mov ax, 0x1003
    mov bl, 0x00
    int 0x10

chaos_loop:
    ; --- НЕПРЕРЫВНЫЙ ДИКИЙ ПИСК И СКРЕЖЕТ ---
    in al, 0x61
    or al, 3
    out 0x61, al

    ; Программируем таймер звука на случайные адские частоты
    mov al, 0xB6
    out 0x43, al
    in al, 0x40             ; Берем случайное число из таймера процессора для звука
    out 0x42, al            ; Младший байт частоты
    in al, 0x40             ; Снова берем случайный шум
    and al, 0x03            ; Ограничиваем верхний предел, чтобы писк оставался высоким и мерзким
    inc al                  ; Защита от нуля
    out 0x42, al            ; Старший байт частоты

    ; Настройка сегмента видеопамяти BIOS
    mov ax, 0xB800
    mov es, ax
    
    ; --- ЭФФЕКТ БЕШЕНОГО ДРОЖАНИЯ ВСЕГО ЭКРАНА ---
    in al, 0x40             ; Читаем шум
    and ax, 63              ; Увеличиваем диапазон тряски (до 63 знакомест)
    shl ax, 1               ; В байты
    mov di, ax              ; Смещаем начало отрисовки экрана

.screen_fill:
    ; --- СЛУЧАЙНЫЙ ASCII СИМВОЛ ---
    in al, 0x40             ; Генерируем случайный байт для символа
    ; Исключаем управляющие символы (ноль, пробелы и т.д.), берем только мясо из таблицы ASCII
    cmp al, 33
    jbe .fix_char
    jmp .char_ok
.fix_char:
    add al, 64              ; Превращаем невидимые символы в видимые глитчи
.char_ok:

    ; --- СЛУЧАЙНЫЙ ЦВЕТ РАДУГИ (ФОН + ТЕКСТ) ---
    mov ah, al              ; Временно сохраняем символ в AH
    in al, 0x40             ; Генерируем случайный цвет для текущего символа
    mov ch, al              ; Цветовой атрибут теперь в CH
    mov al, ah              ; Возвращаем символ в AL

    ; Записываем результат в видеопамять
    mov [es:di], al         ; Случайный глитч-символ
    mov [es:di+1], ch       ; Случайный взрыв цвета радуги
    add di, 2

    cmp di, 4000            ; Заливаем экран до самого конца
    jb .screen_fill

    ; Сразу без задержек прыгаем на генерацию нового кадра хаоса!
    jmp chaos_loop          

; Сигнатура MBR загрузчика (ровно 512 байт для QEMU)
times 510-($-$$) db 0
dw 0xAA55
